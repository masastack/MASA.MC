    public static string GetFailureReasonDisplay(string? reason, bool useFailureReasonMapping)
    {
        if (string.IsNullOrWhiteSpace(reason))
        {
            return string.Empty;
        }

        var trimmed = reason.Trim();
        if (!useFailureReasonMapping)
        {
            return trimmed;
        }

        return FailureReasonMap.TryGetValue(trimmed, out var description)
            ? description
            : trimmed;
    }

    public static bool TryGetDescription(string? code, out string description)
    {
        if (string.IsNullOrWhiteSpace(code))
        {
            description = string.Empty;
            return false;
        }

        return FailureReasonMap.TryGetValue(code.Trim(), out description!);
    }

